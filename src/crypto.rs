//! Session-stream encryption, byte-for-byte compatible with hbb_common's
//! `Encrypt` (KX v0): XSalsa20-Poly1305 (secretbox) with a per-direction
//! little-endian sequence nonce in the first 8 of the 24 nonce bytes.
//! Counters start at 0 and increment BEFORE use, so the first frame each
//! side sends/decrypts uses sequence 1. Encryption wraps the protobuf and
//! sits inside the length-prefix framing: wire = frame(seal(protobuf)).
//!
//! Golden vectors in the tests were produced by the real hbb_common
//! (rustdesk 1.4.5 pin, commit 073403e) `tcp::Encrypt`.

use anyhow::Result;
use sodiumoxide::crypto::secretbox;

pub struct Encrypt {
    key: secretbox::Key,
    send_seq: u64,
    recv_seq: u64,
}

impl Encrypt {
    pub fn new(key: secretbox::Key) -> Self {
        Self {
            key,
            send_seq: 0,
            recv_seq: 0,
        }
    }

    pub fn enc(&mut self, data: &[u8]) -> Vec<u8> {
        self.send_seq += 1;
        secretbox::seal(data, &nonce(self.send_seq), &self.key)
    }

    /// Mirrors hbb_common: payloads of length <= 1 pass through untouched.
    pub fn dec(&mut self, sealed: &[u8]) -> Result<Vec<u8>> {
        if sealed.len() <= 1 {
            return Ok(sealed.to_vec());
        }
        self.recv_seq += 1;
        secretbox::open(sealed, &nonce(self.recv_seq), &self.key)
            .map_err(|_| anyhow::anyhow!("decryption error (sequence desync or wrong key)"))
    }
}

fn nonce(seq: u64) -> secretbox::Nonce {
    let mut n = [0u8; secretbox::NONCEBYTES];
    n[..8].copy_from_slice(&seq.to_le_bytes());
    secretbox::Nonce(n)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn key() -> secretbox::Key {
        secretbox::Key(core::array::from_fn(|i| (i * 7 + 3) as u8))
    }

    fn unhex(s: &str) -> Vec<u8> {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }

    /// Vectors generated by hbb_common::tcp::Encrypt with the same fixed key:
    /// enc("hello world") at seq 1, enc("") at seq 2, enc([42;300]) at seq 3.
    #[test]
    fn golden_vectors_match_hbb_common() {
        let mut e = Encrypt::new(key());
        assert_eq!(
            hex::encode(e.enc(b"hello world")),
            "7e224504365ec5ca8712f05c111e2ce230366110603d424199c529"
        );
        assert_eq!(
            hex::encode(e.enc(b"")),
            "3a1cd9fdd83bad74cc11680d00f5b3e9"
        );
        assert_eq!(
            hex::encode(e.enc(&vec![42u8; 300])),
            "f53c83d17dd0a034dd50b21d9320b9391ed2b6f9cfbc335c4312a08842bd2f86baa2730bd08dd2d2c1c04dab67d9c63328846589647c5e11e5d79bcdb7aff8f28d16ad350b2efc9c78c61e7644e7e9a699297f03c45bf351c46bf751db7cf05bdbeac5ee88dbd81a558c57256f424a925f011ada159225b3eebbf83ebc7f1856f5fb37fbb379ea094e5f911d6a971ebdab9e9232bd2da14098c0bd5ea95d2789d2cb35fbe2e77a920f8ee3bc7526a2e82296723b99e8ccf5584eb9155624305a3f1d81d7afe5939e2a8291d2430bf08020c3c2af2206ceb505ab2ddbf6211bb779d1a0881e3579ec8bbba2ebf90291b7ecbf4f3fa9341e973743ea1a4a2aca573fdcd75020543a0f5190a1d66c7b2549a4566046c8b482ad2e495b869caa9f237b86d70699bd47e77332d0afd93cfc65696c455026222e9e69c53659"
        );
    }

    #[test]
    fn decrypts_hbb_common_output() {
        // hbb_common seal("roundtrip check") at seq 1 with the fixed key
        let mut d = Encrypt::new(key());
        assert_eq!(
            d.dec(&unhex("86fa5f66de4778b67700fb6172719f322a3c78126b6947479b892eef2f6ae5"))
                .unwrap(),
            b"roundtrip check"
        );
    }

    #[test]
    fn sequence_desync_is_detected() {
        let mut a = Encrypt::new(key());
        let mut b = Encrypt::new(key());
        // receiver decrypts the SECOND sender frame first -> nonce mismatch
        let _s1 = a.enc(b"one");
        let s2 = a.enc(b"two");
        assert!(b.dec(&s2).is_err());
    }

    #[test]
    fn tiny_payloads_pass_through() {
        let mut e = Encrypt::new(key());
        assert_eq!(e.dec(&[0u8]).unwrap(), vec![0u8]);
        assert_eq!(e.dec(&[]).unwrap(), Vec::<u8>::new());
    }

    #[test]
    fn wrong_key_fails() {
        let mut a = Encrypt::new(key());
        let mut b = Encrypt::new(secretbox::Key([9u8; 32]));
        let s = a.enc(b"secret");
        assert!(b.dec(&s).is_err());
    }
}
